export function applyLanguage(root: HTMLElement, language: 'ru' | 'en') {
  document.documentElement.lang = language;
  if (language !== 'en') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const value = node.textContent ?? '';
    const trimmed = value.trim();
    if (en[trimmed]) node.textContent = value.replace(trimmed, en[trimmed]);
  }
  root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>('[placeholder]').forEach((field) => {
    if (placeholders[field.placeholder]) field.placeholder = placeholders[field.placeholder];
  });
}
